const emailLayout = require('./emailLayout')

const escapeHtml = (value = '') => {
  return String(value).replace(/[&<>"']/g, (char) => {
    const entities = {
      '&': '&amp;',
      '<': '&lt;',
      '>': '&gt;',
      '"': '&quot;',
      "'": '&#39;',
    }

    return entities[char]
  })
}

const invoiceEmail = ({ invoice, company, customer }) => {
  const invoiceNumber = escapeHtml(invoice.invoiceNumber)
  const companyName = escapeHtml(company.companyName)
  const customerName = escapeHtml(customer.customerName)
  const grandTotal = Number(invoice.grandTotal || 0).toFixed(2)
  const balanceAmount = Number(invoice.balanceAmount || 0).toFixed(2)
  const currency = escapeHtml(company.currency || 'INR')

  const content = `
    <p>Hello <strong>${customerName}</strong>,</p>

    <p>
      Please find attached your invoice issued by
      <strong>${companyName}</strong>.
    </p>

    <table width="100%" cellpadding="0" cellspacing="0"
      style="border-collapse:collapse;margin:22px 0;background:#faf9ff;border:1px solid #eeeaf7;">
      <tr>
        <td style="padding:12px;border-bottom:1px solid #eeeaf7;color:#64748b;">
          Invoice Number
        </td>
        <td style="padding:12px;border-bottom:1px solid #eeeaf7;text-align:right;font-weight:700;color:#111827;">
          ${invoiceNumber}
        </td>
      </tr>

      <tr>
        <td style="padding:12px;border-bottom:1px solid #eeeaf7;color:#64748b;">
          Invoice Date
        </td>
        <td style="padding:12px;border-bottom:1px solid #eeeaf7;text-align:right;color:#111827;">
          ${new Date(invoice.invoiceDate).toLocaleDateString('en-IN')}
        </td>
      </tr>

      <tr>
        <td style="padding:12px;border-bottom:1px solid #eeeaf7;color:#64748b;">
          Due Date
        </td>
        <td style="padding:12px;border-bottom:1px solid #eeeaf7;text-align:right;color:#111827;">
          ${invoice.dueDate ? new Date(invoice.dueDate).toLocaleDateString('en-IN') : 'Not specified'}
        </td>
      </tr>

      <tr>
        <td style="padding:12px;border-bottom:1px solid #eeeaf7;color:#64748b;">
          Invoice Amount
        </td>
        <td style="padding:12px;border-bottom:1px solid #eeeaf7;text-align:right;font-weight:700;color:#111827;">
          ${currency} ${grandTotal}
        </td>
      </tr>

      <tr>
        <td style="padding:12px;color:#64748b;">
          Outstanding Amount
        </td>
        <td style="padding:12px;text-align:right;font-weight:700;color:#6d28d9;">
          ${currency} ${balanceAmount}
        </td>
      </tr>
    </table>

    <p>
      The invoice PDF is attached to this email for your reference.
      Kindly review the invoice and arrange payment by the due date.
    </p>

    <p>
      Thank you for your business.
    </p>

    <p style="margin-top:24px;">
      Regards,<br />
      <strong>${companyName}</strong>
    </p>
  `

  return emailLayout({
    preheader: `Invoice ${invoiceNumber} from ${companyName}`,
    title: 'Your Invoice is Ready',
    subtitle: 'Invoice Notification',
    content,
    footerNote: 'This email contains an invoice generated by MineERP.',
  })
}

module.exports = invoiceEmail
